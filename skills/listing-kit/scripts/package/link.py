"""Install a relocatable listing-kit launcher."""
import argparse
import os
from pathlib import Path
import shlex
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generated_file import write_generated

KIT = Path(__file__).resolve().parents[2]
MARKER = "# Generated by listing-kit link"


def owned(path):
    if path.is_symlink() or not path.is_file():
        return False
    with path.open("rb") as stream:
        if not stream.readline(256).endswith(b"\n"):
            return False
        return stream.readline(256).rstrip(b"\n") == MARKER.encode()


def launcher_text():
    # Embed the same lookup as the Git hook so a removed kit is recoverable.
    lookup = (KIT / "scripts/lib/install_lookup.py").read_text()
    return f"""#!/usr/bin/env bash
{MARKER}
recorded={shlex.quote(str(KIT))}
preferred="${{LISTING_KIT_HOME:-$recorded}}"
case "$preferred" in
  /*) if [ -x "$preferred/bin/listing-kit" ]; then exec "$preferred/bin/listing-kit" "$@"; fi ;;
esac
cli="$(python3 -I -B - "$recorded" <<'PYLAUNCH'
{lookup}
import sys

def has_cli(kit):
    return version(kit) and os.access(kit / "bin/listing-kit", os.X_OK)

recorded = Path(sys.argv[1])
try:
    kit = find_kit(recorded, channel_for(recorded), has_cli)
    print(kit / "bin/listing-kit")
except (Blocked, OSError) as exc:
    sys.exit(str(exc))
PYLAUNCH
)" || exit 3
exec "$cli" "$@"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", type=Path, default=Path.home() / ".local/bin")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args()
    directory = args.dir.expanduser().resolve()
    path = directory / "listing-kit"
    if path == KIT / "bin/listing-kit":
        parser.exit(1, "Choose a launcher directory outside the kit's bin directory\n")
    if args.remove:
        if owned(path):
            path.unlink()
        elif os.path.lexists(path):
            parser.exit(1, f"Refusing to remove foreign launcher: {path}\n")
        return
    if os.path.lexists(path) and not (owned(path) or args.force):
        parser.exit(1, f"Refusing to replace foreign launcher: {path} (use --force)\n")
    directory.mkdir(parents=True, exist_ok=True)
    write_generated(path, launcher_text(), 0o755, args.force or owned(path))
    print(f"Installed {path}")
    if directory in [Path(d).resolve() for d in os.get_exec_path()]:
        print(f"{directory} is on PATH")
    else:
        print(f"{directory} is not on PATH. Add this line to your shell profile:")
        print(f'export PATH={shlex.quote(str(directory))}:"$PATH"')


if __name__ == "__main__":
    try:
        main()
    except OSError as exc:
        sys.exit(str(exc))
