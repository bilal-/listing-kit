"""Generate a store listing pipeline at the app's repository root."""
import argparse
import os
from pathlib import Path
import re
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generated_file import write_generated

KIT = Path(__file__).resolve().parents[2]
MARKER = "# Generated by listing-kit ci init"


sys.path.insert(0, str(KIT / "scripts/lib"))
from plan import listing_roots


def repository(app):
    result = subprocess.run(["git", "-C", str(app), "rev-parse", "--show-toplevel"],
                            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    return Path(os.fsdecode(result.stdout.rstrip(b"\n"))).resolve() if not result.returncode else app


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--provider", choices=("github", "gitlab"), required=True)
    parser.add_argument("--app-root", type=Path, default=Path("."))
    parser.add_argument("--kit-ref", required=True, help="pass a released tag or a commit SHA containing the listing-kit command")
    parser.add_argument("--force", action="store_true", help="replace a workflow marked as generated by listing-kit")
    args = parser.parse_args()
    app = args.app_root.resolve()
    if not app.is_dir():
        parser.error("app root must be an existing directory")
    repo = repository(app)
    relative = app.relative_to(repo).as_posix()
    # Paths are literals in both the CI expression language and glob filters.
    if not relative.isprintable() or any(char in relative for char in "*?[]!+{}$\\"):
        parser.error("app path contains CI expression or glob characters")
    ref = args.kit_ref
    if (ref.startswith(("-", "+")) or "$" in ref or not ref.isprintable()
            or subprocess.run(["git", "check-ref-format", "refs/tags/" + ref]).returncode):
        parser.error("expected a literal kit tag, branch name or commit SHA")
    include = False
    if args.provider == "github":
        path = repo / ".github/workflows/listing.yml"
    else:
        path = repo / ".gitlab-ci.yml"
        if os.path.lexists(path):
            include = True
            path = repo / "listing-kit.gitlab-ci.yml"
    if path.parent != path.parent.resolve():
        parser.error("refusing to write through a symlinked workflow directory")
    template = (KIT / "templates/ci" / (args.provider + ".yml")).read_text()
    values = {"APP_PREFIX": "" if relative == "." else relative + "/",
              "APP_ROOT": "./" + relative if relative.startswith("-") else relative, "KIT_REF": ref}
    suffix = "/**" if args.provider == "github" else "/**/*"
    indent = "      " if args.provider == "github" else "        "
    filters = []
    for directory in listing_roots(app):
        folder = str(directory)
        if any(char in folder for char in "*?[]!+{}$\\"):
            parser.error("listing path contains CI expression or glob characters")
        literal = (values["APP_PREFIX"] + folder + suffix).replace("'", "''")
        filters.append(indent + "- '" + literal + "'")
    values = {key: value.replace("'", "''") for key, value in values.items()}
    values["LISTING_FILTERS"] = "\n".join(filters)
    content = re.sub(r"__(APP_PREFIX|APP_ROOT|KIT_REF|LISTING_FILTERS)__", lambda m: values[m[1]], template)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = MARKER + "\n" + content
    overwrite = False
    if os.path.lexists(path):
        if not path.is_symlink() and path.is_file():
            with path.open("rb") as stream:
                overwrite = stream.readline(256).rstrip(b"\r\n") == MARKER.encode()
        if not overwrite:
            parser.exit(1, f"Refusing to replace {path}: expected a regular file with the listing-kit marker\n")
        if not args.force:
            parser.exit(1, f"{path} already exists (use --force to replace it)\n")
    write_generated(path, content, 0o644, overwrite)
    print(f"Wrote {path}")
    if include:
        print("include: [{local: 'listing-kit.gitlab-ci.yml'}]")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as exc:
        sys.exit(str(exc))
